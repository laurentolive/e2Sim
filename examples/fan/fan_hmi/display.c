static uint16_t *s_fb;

static void fill(unsigned x, unsigned y, unsigned w, unsigned h, uint16_t c)
{
    for (unsigned j = y; (j < y + h) && (j < HAL_LCD_HEIGHT); j++)
    {
        for (unsigned i = x; (i < x + w) && (i < HAL_LCD_WIDTH); i++)
        {
            s_fb[j * HAL_LCD_WIDTH + i] = c;
        }
    }
}

static unsigned text(unsigned x, unsigned y, const char *s, uint16_t c, unsigned scale)
{
    for (; *s != '\0'; s++)
    {
        char ch = *s;
        if ((ch >= 'a') && (ch <= 'z'))
        {
            ch = (char)(ch - 'a' + 'A');
        }
        if ((ch < ' ') || (ch > 'Z'))
        {
            ch = '?';
        }
        const uint8_t *g = s_font[ch - ' '];
        for (unsigned col = 0; col < 5u; col++)
        {
            for (unsigned row = 0; row < 8u; row++)
            {
                if ((g[col] >> row) & 1u)
                {
                    fill(x + col * scale, y + row * scale, scale, scale, c);
                }
            }
        }
        x += 6u * scale;
    }
    return x;
}

void display_Init(void)
{
    halLcd_Init();
    /* controller reset time: busy wait on the HAL microsecond counter */
    uint32_t t0 = halTimer_GetUs();
    while ((uint32_t)(halTimer_GetUs() - t0) < HAL_LCD_RESET_US)
    {
    }
    s_fb = halLcd_GetFrameBuffer();
    fill(0, 0, HAL_LCD_WIDTH, HAL_LCD_HEIGHT, C_BLACK);
    halLcd_Update();
}

static const char *fault_text(void)
{
    if (app.wdtReset)
    {
        return "WDT RESET";
    }
    if (app.fault & APP_FAULT_TEMP)
    {
        return "OVER TEMP";
    }
    if (app.fault & APP_FAULT_LINK)
    {
        return "LINK LOST";
    }
    if (app.fault & APP_FAULT_MOTOR)
    {
        return "MOTOR FAULT";
    }
    if (app.fault & APP_FAULT_SENSOR)
    {
        return "SENSOR";
    }
    if (app.fault & APP_FAULT_BAT)
    {
        return "BAT LOW";
    }
    return NULL;
}

void display_Refresh(void)
{
    char buf[24];
    fill(0, 0, HAL_LCD_WIDTH, HAL_LCD_HEIGHT, C_BLACK);
    if (app.shuttingDown)
    {
        text(46, 25, "BYE", C_WHITE, 2);
        halLcd_Update();
        return;
    }

    /* header: state and battery */
    fill(0, 0, HAL_LCD_WIDTH, 10, C_BLUE);
    text(2, 1, app.running ? "FAN ON" : "FAN OFF", app.running ? C_GREEN : C_GREY, 1);
    snprintf(buf, sizeof(buf), "%3u%%", (unsigned)app.batPercent);
    text(HAL_LCD_WIDTH - 26u, 1, buf, (app.fault & APP_FAULT_BAT) ? C_RED : C_WHITE, 1);

    /* speed */
    if (app.running)
    {
        snprintf(buf, sizeof(buf), "SPEED %u", (unsigned)app.speedLevel);
        text(4, 14, buf, C_WHITE, 2);
    }
    else
    {
        text(4, 14, "STANDBY", C_GREY, 2);
    }
    snprintf(buf, sizeof(buf), "%u RPM", (unsigned)app.rpmMeasured);
    text(4, 34, buf, C_YELLOW, 1);
    int t = app.temp_dC;
    int a = (t < 0) ? -t : t;
    snprintf(buf, sizeof(buf), "TEMP %s%d.%dC", (t < 0) ? "-" : "", a / 10, a % 10);
    text(4, 44, buf, C_WHITE, 1);

    const char *f = fault_text();
    if (f != NULL)
    {
        text(4, 55, f, C_RED, 1);
    }
    halLcd_Update();
}
