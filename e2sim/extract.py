"""Sources, include directories and defines of a firmware, taken from its target build (spec §11).

Input: the target makefile run in dry mode (`make -n -B -w`: nothing is compiled, no compiler needed), or a
compile_commands.json. Output: a make fragment for mk/e2sim.mk, without the MCU HAL and the BSP (exclude
patterns), plus the e2Sim adapter given by the user.

    e2sim extract --make "make -C ../firmware" --exclude "*/Hw/MCU/*" --exclude "*/BSP/*" \\
                  --name my_product --adapter Hw/MCU/E2SIM --out e2sim_sources.mk
"""

from __future__ import annotations

import fnmatch
import json
import os
import re
import shlex
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

C_EXT = (".c",)
ENTER = re.compile(r"make(?:\[\d+\])?: Entering directory [`'\"](.+?)['\"]")
LEAVE = re.compile(r"make(?:\[\d+\])?: Leaving directory")


@dataclass
class Compile:
    source: Path
    includes: list[Path] = field(default_factory=list)
    defines: list[str] = field(default_factory=list)


def _split(line: str) -> list[str]:
    toks = shlex.split(line.replace("\\", "/"), posix=True)
    return toks


def parse_command(line: str, cwd: Path) -> Compile | None:
    """One compiler command line -> its C source, -I, -D (other options ignored: target specific)."""
    if not re.search(r"(gcc|clang|cc|armcc|iccarm)(\.exe)?['\"]?\s", line + " "):
        return None
    try:
        toks = _split(line)
    except ValueError:
        return None
    src, incs, defs = None, [], []
    i = 0
    while i < len(toks):
        t = toks[i]
        if t in ("-I", "-isystem", "-iquote") and i + 1 < len(toks):
            incs.append(toks[i + 1])
            i += 2
            continue
        if t in ("-D",) and i + 1 < len(toks):
            defs.append(toks[i + 1])
            i += 2
            continue
        if t.startswith("-I") and len(t) > 2:
            incs.append(t[2:])
        elif t.startswith("-D") and len(t) > 2:
            defs.append(t[2:])
        elif not t.startswith("-") and t.lower().endswith(C_EXT):
            src = t
        i += 1
    if src is None:
        return None
    resolve = lambda p: (cwd / p).resolve() if not Path(p).is_absolute() else Path(p).resolve()  # noqa: E731
    return Compile(source=resolve(src), includes=[resolve(p) for p in incs], defines=defs)


def from_make(command: str, cwd: Path) -> list[Compile]:
    """Run the target build in dry mode and read its compiler commands."""
    args = shlex.split(command.replace("\\", "/")) + ["-n", "-B", "-w"]
    r = subprocess.run(args, cwd=cwd, capture_output=True, text=True, errors="replace")
    if r.returncode != 0 and not r.stdout:
        raise RuntimeError(f"{command}: {r.stderr.strip()}")
    out, dirs = [], [Path(cwd).resolve()]
    for line in r.stdout.splitlines():
        m = ENTER.search(line)
        if m:
            dirs.append(Path(m.group(1)).resolve())
            continue
        if LEAVE.search(line) and len(dirs) > 1:
            dirs.pop()
            continue
        c = parse_command(line, dirs[-1])
        if c is not None:
            out.append(c)
    return out


def from_compdb(path: Path) -> list[Compile]:
    out = []
    for e in json.loads(Path(path).read_text(encoding="utf-8")):
        cwd = Path(e.get("directory", Path(path).parent))
        line = e.get("command") or " ".join(shlex.quote(a) for a in e.get("arguments", []))
        if "file" in e and e["file"] not in line:
            line += " " + e["file"]
        c = parse_command(line, cwd)
        if c is not None:
            out.append(c)
    return out


def _excluded(p: Path, patterns: list[str]) -> bool:
    s = p.as_posix()
    return any(fnmatch.fnmatch(s, pat) or fnmatch.fnmatch(s.lower(), pat.lower()) for pat in patterns)


def make_fragment(compiles: list[Compile], name: str, out_dir: Path, exclude: list[str] = (),
                  adapter: list[Path] = (), drop_defines: list[str] = ()) -> str:
    """Make fragment: <NAME>_SRCS, <NAME>_INCS, <NAME>_DEFS, then the e2sim_firmware call."""
    out_dir = Path(out_dir).resolve()
    rel = lambda p: Path(os.path.relpath(p, out_dir)).as_posix()  # noqa: E731
    srcs, incs, defs = [], [], []
    for c in compiles:
        if _excluded(c.source, exclude):
            continue
        if c.source not in srcs:
            srcs.append(c.source)
        for i in c.includes:
            if i not in incs and not _excluded(i, exclude):
                incs.append(i)
        for d in c.defines:
            if d not in defs and d.split("=")[0] not in drop_defines:
                defs.append(d)
    ad_srcs, ad_incs = [], []
    for a in adapter:
        a = Path(a).resolve()
        ad_incs.append(a)
        ad_srcs += sorted(a.glob("*.c"))
    var = re.sub(r"\W", "_", name).upper()
    lines = [f"# generated by e2sim extract - {len(srcs)} sources of the target build, "
             f"{len(ad_srcs)} of the e2Sim adapter", ""]

    def block(key, items):
        lines.append(f"{var}_{key} := \\")
        lines.extend(f"    {x} \\" for x in items)
        lines.append("")

    block("SRCS", [rel(s) for s in srcs + ad_srcs])
    block("INCS", [rel(i) for i in ad_incs + incs])
    block("DEFS", defs)
    lines.append(f"$(eval $(call e2sim_firmware,{name},$({var}_SRCS),$({var}_INCS),$({var}_DEFS)))")
    return "\n".join(lines) + "\n"
